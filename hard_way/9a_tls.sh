#!/bin/bash
#
# STEP 9a — TLS bootstrapping, control plane side: token + RBAC
#
# WHY THIS EXISTS
# Step 8a issues each kubelet's certificate by hand on the control plane. That
# does not scale and the certs never rotate. TLS bootstrapping replaces it:
# a new node starts with nothing but a short-lived shared *token*, uses it to
# submit a CertificateSigningRequest, and gets back a proper per-node
# certificate signed by the cluster CA (by the controller manager, using the
# ca.key shipped in step 2 — see --cluster-signing-key-file in 6a).
#
# This script sets up the three things that have to exist before a node can do
# that:
#   1. the bootstrap token itself,
#   2. permission for token-holders to *create* CSRs,
#   3. permission for those CSRs to be *auto-approved* (otherwise an admin would
#      have to run `kubectl certificate approve` for every node, every renewal).
#
# Run this on controlplane01. It is the alternative to 8a — use 9a + 9b, or
# 8a + 8b, not both.

# Tokens are deliberately short-lived; a leaked long-lived token is a way into
# the cluster. 7 days is enough to add nodes during a build. The tokencleaner
# controller (enabled in 6a) deletes it once this passes.
EXPIRATION=$(date -u --date "+7 days" +"%Y-%m-%dT%H:%M:%SZ")

# A bootstrap token is just a Secret in kube-system with a rigid shape. The
# API server (started with --enable-bootstrap-token-auth in step 6a) reads these
# and accepts "<token-id>.<token-secret>" as a bearer token.
#
# The two halves have fixed formats: token-id is 6 chars, token-secret is 16.
# Node 9b presents exactly "07401b.f395accd246ae52d" — these values must match.
cat > bootstrap-token-07401b.yaml <<EOF
apiVersion: v1
kind: Secret
metadata:
  # Name MUST be of form "bootstrap-token-<token id>"
  name: bootstrap-token-07401b
  namespace: kube-system

# Type MUST be 'bootstrap.kubernetes.io/token'
type: bootstrap.kubernetes.io/token
stringData:
  # Human readable description. Optional.
  description: "The default bootstrap token generated by 'kubeadm init'."

  # Token ID and secret. Required.
  token-id: 07401b
  token-secret: f395accd246ae52d

  # Expiration. Optional.
  expiration: ${EXPIRATION}

  # Allowed usages.
  usage-bootstrap-authentication: "true"
  usage-bootstrap-signing: "true"

  # Extra groups to authenticate the token as. Must start with "system:bootstrappers:"
  # A client presenting this token is authenticated as user
  # system:bootstrap:07401b in groups system:bootstrappers and
  # system:bootstrappers:worker. The ClusterRoleBindings below grant rights to
  # that *group*, which is how the token gets its (deliberately tiny) powers.
  auth-extra-groups: system:bootstrappers:worker
EOF


kubectl create -f bootstrap-token-07401b.yaml --kubeconfig admin.kubeconfig

# 1. Let a bootstrapping node submit a CSR at all.
#    Without this the kubelet authenticates with the token and is then denied
#    when it tries to create its CertificateSigningRequest.
kubectl create clusterrolebinding create-csrs-for-bootstrapping \
  --clusterrole=system:node-bootstrapper \
  --group=system:bootstrappers \
  --kubeconfig admin.kubeconfig

# 2. Auto-approve those initial CSRs.
#    Creating a CSR is not enough — something must approve it before the signer
#    will issue a certificate. This binding delegates approval to the controller
#    manager for any CSR from a bootstrapping node, so node provisioning needs
#    no human in the loop.
kubectl create clusterrolebinding auto-approve-csrs-for-group \
  --clusterrole=system:certificates.k8s.io:certificatesigningrequests:nodeclient \
  --group=system:bootstrappers \
  --kubeconfig admin.kubeconfig

# 3. Auto-approve *renewals*.
#    Note the different group (system:nodes, i.e. already-joined nodes) and the
#    "selfnodeclient" role — a node may only renew a certificate for itself.
#    This is what makes rotateCertificates in 9b work unattended; without it
#    every kubelet cert would silently expire and the node would drop out.
kubectl create clusterrolebinding auto-approve-renewals-for-nodes \
  --clusterrole=system:certificates.k8s.io:certificatesigningrequests:selfnodeclient \
  --group=system:nodes \
  --kubeconfig admin.kubeconfig
